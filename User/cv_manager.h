#ifndef CV_MANAGER_H
#define CV_MANAGER_H

#include "decoder_config.h"

// ============================================================================
//  CV (Configuration Variable) 管理用マクロ、変数宣言
// ============================================================================

// ----------------------------------------------------------------------------
// 管理、サポートするCVの総数 (CV1 ～ CV64 までを対象とします)
// ----------------------------------------------------------------------------
// 【補足】
// NMRA規格では1024個以上のCVが定義できますが、ワンコインデコーダXの
// 主要な機能（アドレス、速度カーブ、モメンタム、BEMF、ファンクションマッピング）は
// CV1〜CV64の範囲に収まるため、Flashメモリ領域の節約とRAMの消費抑制を
// 目的としてサイズを64バイトに制限しています。
#define CV_DATA_SIZE 64

// ============================================================================
//  グローバル変数 (外部参照用)
// ============================================================================

// ----------------------------------------------------------------------------
// CV値のRAMキャッシュ (cv_cache)
// ----------------------------------------------------------------------------
// 【役割】マイコン起動時にFlash(EEPROM領域)から読み出したCV値を保持しておく配列です。
//         ※ 配列のインデックスとCV番号はずれており、[0]がCV1、[63]がCV64に対応します。
// 【なぜ必要か】
// Flashメモリへの直接アクセスは遅く、特に書き込み中は処理がブロックされて
// DCC信号の受信（割り込み）が破綻してしまいます。そのため、普段の動作時は
// このRAM上の高速な配列（キャッシュ）を参照して動作します。
// 【注意点】
// DCC割り込み処理（パケット受信）内から非同期にアクセス、変更されるため、
// コンパイラの最適化（古い値を使い回す処理）を防ぐ目的で `volatile` 修飾子を付与しています。
extern volatile uint8_t cv_cache[CV_DATA_SIZE];

// ----------------------------------------------------------------------------
// Paged Mode (ページモード) 処理用レジスタ (page_register)
// ----------------------------------------------------------------------------
// 【役割】古いDCCコマンドステーションによる「ページモードCVアクセス」の際、
//         現在どのページ番号を操作しているかを一時的に記憶するための変数です。
extern volatile uint8_t page_register;

// ----------------------------------------------------------------------------
// 現在のポイント（分岐器）の開通方向を保持する変数 (current_point_dir)
// ----------------------------------------------------------------------------
// 【役割】`TARGET_8PIN_POINT` 選択時（ポイントデコーダ動作時）に使用され、
//         現在の開通方向（0:直進 / 1:分岐など）を記憶します。
// 【補足】電源を切っても前回の状態を記憶しておくため、値の変更時に
//         CV領域の空きスペース（CV64など）を利用してFlashに保存されます。
//         次回起動時はこの値を読み出し、元の状態を復元します。
extern uint8_t current_point_dir;

// ============================================================================
//  CV管理、EEPROM操作関数プロトタイプ
// ============================================================================

// ----------------------------------------------------------------------------
// 関数名: EEPROM_Init
// 役割  : 起動時の初期化処理を行います。
//         電源投入時に呼ばれ、Flashメモリから設定値を `cv_cache` にロードします。
//         初回起動時（またはCV8が0xFFなど未初期化と判定された場合）は、
//         工場出荷時のデフォルト設定配列から値をコピーし、Flashを初期化します。
// ----------------------------------------------------------------------------
void EEPROM_Init(void);

// ----------------------------------------------------------------------------
// 関数名: EEPROM_SaveAll
// 役割  : CV値の一括保存処理を行います。
//         `cv_cache` の内容をFlashメモリの専用領域へ一括で書き込み（退避）します。
//         ※ 書き込み中にDCC割り込みが発生するとマイコンがクラッシュする恐れがあるため、
//            関数内部で一時的にDCC割り込みを禁止・再開する保護処理が行われます。
// ----------------------------------------------------------------------------
void EEPROM_SaveAll(void);

// ----------------------------------------------------------------------------
// 関数名: Read_CV
// 役割  : 指定したCV番号の値を読み出します。
// 引数  : cv_number = 読み出したいDCCのCV番号 (1 ～ 64)
// 戻り値: キャッシュされているCVの値。範囲外のCV番号が指定された場合は安全のため 0 を返します。
// 補足  : 内部でCV番号を配列のインデックス番号(cv_number - 1)に変換して処理します。
// ----------------------------------------------------------------------------
uint8_t Read_CV(uint16_t cv_number);

// ----------------------------------------------------------------------------
// 関数名: Write_CV
// 役割  : 指定したCV番号に新しい値を書き込みます。
// 引数  : cv_number = 書き込みたいCV番号 (1 ～ 64), value = 書き込む値
// 補足  : 
//         ・特殊動作: CV8 に 8 を書き込んだ場合は、ファクトリーリセット処理を実行します。
//         ・保護機能: CV7(バージョン), CV8(メーカーID)への不用意な上書きをガードします。
//         ・寿命対策: Flashメモリは書き換え回数に寿命（約10万回）があるため、
//                     現在のキャッシュ値と比較し、実際に値が変化した場合のみ `EEPROM_SaveAll()` を呼び出します。
// ----------------------------------------------------------------------------
void Write_CV(uint16_t cv_number, uint8_t value);

#endif