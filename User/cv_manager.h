#ifndef CV_MANAGER_H
#define CV_MANAGER_H

#include "decoder_config.h"

// ============================================================================
//  CV (Configuration Variable) 管理用マクロ、変数宣言
// ============================================================================

// 管理、サポートするCVの総数 (CV1 ～ CV64 までを対象とします)
#define CV_DATA_SIZE 64

// ----------------------------------------------------------------------------
//  グローバル変数 (外部参照用)
// ----------------------------------------------------------------------------

// CV値のRAMキャッシュ
// マイコン起動時にFlash(EEPROM領域)から読み出したCV値を保持しておく配列です。
// ※ 配列のインデックスとCV番号はずれており、[0]がCV1、[63]がCV64に対応します。
// DCC割り込み処理内から非同期にアクセス、変更されるため、コンパイラの最適化を防ぐ
// 目的で `volatile` 修飾子を付与しています。
extern volatile uint8_t cv_cache[CV_DATA_SIZE];

// Paged Mode (ページモード) 処理用レジスタ
// 古いDCCコマンドステーションによる「ページモードCVアクセス」の際、
// 現在どのページを操作しているかを一時的に記憶するための変数です。
extern volatile uint8_t page_register;

// 現在のポイント（分岐器）の開通方向を保持する変数
// `TARGET_8PIN_POINT` 選択時に使用されます。
// 電源を切っても前回の状態を記憶しておくため、値の変更時にCV領域(CV64など)に保存されます。
extern uint8_t current_point_dir;

// ============================================================================
//  CV管理、EEPROM操作関数プロトタイプ
// ============================================================================

// 起動時の初期化処理
// 電源投入時に呼ばれ、Flashメモリから設定値を `cv_cache` にロードします。
// 初回起動時（またはCV8が0xFFなど未初期化と判定された場合）は、
// 出荷時のデフォルト設定配列から値をコピーし、Flashを初期化します。
void EEPROM_Init(void);

// CV値の一括保存処理
// `cv_cache` の内容をFlashメモリの専用領域へ書き込み（退避）します。
// ※ 書き込み中に割り込みが発生するとマイコンがクラッシュする恐れがあるため、
//    内部で一時的にDCC割り込みを禁止する処理が行われます。
void EEPROM_SaveAll(void);

// 指定したCV番号の値を読み出す関数
// 引数   : cv_number = 読み出したいCV番号 (1 ～ 64)
// 戻り値 : CVの値。範囲外のCV番号が指定された場合は安全のため 0 を返します。
// 内部でCV番号を配列のインデックス(-1)に変換して処理します。
uint8_t Read_CV(uint16_t cv_number);

// 指定したCV番号に値を書き込む関数
// 引数   : cv_number = 書き込みたいCV番号 (1 ～ 64), value = 書き込む値
// ※ 特殊動作: CV8 に 8 を書き込んだ場合は、ファクトリーリセットを実行します。
// ※ 寿命対策: Flashメモリは書き換え回数に寿命があるため、現在のキャッシュ値と
//    比較し、実際に値が変化した場合のみ `EEPROM_SaveAll()` を呼び出します。
void Write_CV(uint16_t cv_number, uint8_t value);

#endif