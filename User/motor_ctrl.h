#ifndef MOTOR_CTRL_H
#define MOTOR_CTRL_H

#include "decoder_config.h"

// ============================================================================
//  モーター / 速度制御用 グローバル変数
// ============================================================================

// ----------------------------------------------------------------------------
// コマンドステーションから受信した「目標」の進行方向と速度ステップ
// ----------------------------------------------------------------------------
// 【役割】DCC割り込み処理内で、受信したコマンドに従って即座に書き換えられます。
//         cmd_dir   : 目標方向 (1:前進, 0:後進)
//         cmd_speed : 目標速度 (内部128ステップ形式、0=停止, 1=非常停止, 2-126=実速度)
extern uint8_t cmd_dir;   
extern uint8_t cmd_speed; 

// ----------------------------------------------------------------------------
// 現在デコーダが実際に出力している進行方向と速度ステップ
// ----------------------------------------------------------------------------
// 【役割】モータ制御の基本となる「現在値」です。
// 【補足】CV3, CV4によるモメンタム(滑らかな加減速の遅延)や、方向転換時に一度
//         停止させるポーズ処理があるため、必ずしも上記の cmd_dir / cmd_speed
//         とは即座に一致しません。1ms定期タスク内で徐々に目標値に近づいていきます。
extern uint8_t current_dir;
extern uint8_t current_speed;

// ============================================================================
//  各種タイマー、フラグ変数
// ============================================================================

// ----------------------------------------------------------------------------
// ポイントデコーダ時の保護タイマー (guard_timer)
// ----------------------------------------------------------------------------
// 【役割】ソレノイドの焼損やコンデンサの電力枯渇を防ぐため、一度ポイントを
//         切り替えた直後の連続動作を禁止する（ガードする）時間を管理します。
//         1msタスクで減算され、0になるまで次のコマンドを無視します。
extern uint16_t guard_timer;

// ----------------------------------------------------------------------------
// キックスタート機能用のフラグとタイマー
// ----------------------------------------------------------------------------
// 【役割】動き出しが渋いモーターの起動時に、一瞬だけ通常より高い電圧
//         (CV48の強度)をかけて起動をアシストする機能です。
//         is_kicking : 現在キックスタート期間中かどうかのフラグ (1:有効, 0:無効)
//         kick_timer : キックスタートの残り時間(CV47)。1msタスクで減算されます。
extern uint8_t is_kicking;    
extern uint16_t kick_timer;   

// ============================================================================
//  ファンクション (F0 - F12) 状態保持変数
// ============================================================================
// ----------------------------------------------------------------------------
// 【役割】DCCコマンドで受信した各ファンクションボタンのON/OFF状態を保持します。 (1: ON, 0: OFF)
//         これらの状態とCV33-CV46(ファンクションマッピング設定)を照らし合わせる
//         ことで、最終的にどのライト(AUXピン)を光らせるかが決定されます。
// ----------------------------------------------------------------------------
extern uint8_t f0_state, f1_state, f2_state, f3_state, f4_state;
extern uint8_t f5_state, f6_state, f7_state, f8_state;
extern uint8_t f9_state, f10_state, f11_state, f12_state;


// ============================================================================
//  出力制御 関数プロトタイプ
// ============================================================================

// ----------------------------------------------------------------------------
// 関数名: Outputs_Init
// 役割  : 出力ピン、タイマー(PWM)のハードウェア初期化
// 補足  : マイコン起動時に呼ばれ、GPIOやPWM生成用タイマー(TIM1等)を設定します。
//         BEMF機能(20ピン)が有効な場合はADCの初期化もここから呼び出されます。
// ----------------------------------------------------------------------------
void Outputs_Init(void);

// ----------------------------------------------------------------------------
// 関数名: Update_Outputs
// 役割  : 実際のピン(GPIO/PWM)への出力更新
// 補足  : 現在の方向(current_dir)、速度(current_speed)、ファンクション状態に
//         基づき、CV値(Vstart, Vmid, Vhigh等)を加味してDuty比を計算し、
//         ハードウェアレジスタに最終的な出力状態を反映させます。
// ----------------------------------------------------------------------------
void Update_Outputs(void);

// ----------------------------------------------------------------------------
// 関数名: Send_Ack
// 役割  : コマンドステーションへの応答(Ack)パルス送信
// 補足  : プログラミング線路でCVの読み書きに成功した際などに「コマンドを受け付けた」
//         というサインを返すため、モーターやライトを約10ms間だけ駆動し、
//         コマンドステーションが検知できる電流（60mA以上）を消費させます。
// ----------------------------------------------------------------------------
void Send_Ack(void);

// ----------------------------------------------------------------------------
// 関数名: Execute_Turnout
// 役割  : ポイント(分岐器)の駆動実行
// 引数  : target_dir (0: 分岐, 1: 直進など)
// 補足  : ポイントデコーダ専用処理。指定された方向に合わせて、
//         CV3(通電時間)やCV6(出力強度)でソレノイドにパルス電流を流します。
// ----------------------------------------------------------------------------
void Execute_Turnout(uint8_t target_dir);

// ----------------------------------------------------------------------------
// 関数名: Process_1ms_Timer_Tasks
// 役割  : 1msごとの定期タスク処理
// 補足  : メインループ内で1ミリ秒経過するごとに呼び出されます。
//         モメンタム(CV3, CV4による滑らかな加減速)、進行方向転換時のポーズ処理、
//         キックスタートのタイマー減算、BEMFの定期サンプリング等を実行します。
// ----------------------------------------------------------------------------
void Process_1ms_Timer_Tasks(void);

#ifdef HAS_MOTOR_OUTPUT
// ----------------------------------------------------------------------------
// 関数名: Update_PWM_Freq
// 役割  : モーターPWMキャリア周波数の更新
// 補足  : CV9の設定値に基づき、PWMの周波数(32kHz, 8kHz, 2kHz, 500Hz等)を
//         タイマーの分周比(プリスケーラ)と周期(オートリロード)を再計算して変更します。
// ----------------------------------------------------------------------------
void Update_PWM_Freq(void);
#endif

#endif