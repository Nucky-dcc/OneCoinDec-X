#ifndef MOTOR_CTRL_H
#define MOTOR_CTRL_H

#include "decoder_config.h"

// ============================================================================
//  モーター / 速度制御用 グローバル変数
// ============================================================================

// コマンドステーションから受信した「目標」の進行方向と速度ステップ
// DCC割り込み処理内で値が更新されます。
extern uint8_t cmd_dir;   // 目標方向 (1:前進, 0:後進)
extern uint8_t cmd_speed; // 目標速度 (内部128ステップ形式、0=停止, 1=非常停止, 2-126=実速度)

// 現在デコーダが実際に出力している進行方向と速度ステップ
// CV設定によるモメンタム(加減速遅延)や、方向転換時のポーズ処理があるため、
// 必ずしも上記のcmd_dir/cmd_speedと一致するとは限りません。1msタスクで徐々に目標値に近づきます。
extern uint8_t current_dir;
extern uint8_t current_speed;

// ============================================================================
//  各種タイマー、フラグ変数
// ============================================================================

// ポイントデコーダ時の保護タイマー (ミリ秒単位または任意のループ単位)
// ソレノイドの焼損を防ぐため、一度切り替えた直後の連続動作を禁止する（ガードする）期間をカウントダウンします。
extern uint16_t guard_timer;

// キックスタート機能 (渋いモーターを動き出しやすくするために一瞬高い電圧をかける機能) 用の変数
extern uint8_t is_kicking;    // 現在キックスタート期間中かどうかのフラグ (1:有効, 0:無効)
extern uint16_t kick_timer;   // キックスタートの残り時間 (1msタスクで減算されます)

// ============================================================================
//  ファンクション (F0 - F12) 状態保持変数
// ============================================================================
// DCCコマンドで受信した各ファンクションのON/OFF状態を保持します。 (1: ON, 0: OFF)
// これらの状態とCV33-CV46(ファンクションマッピング)を照らし合わせて、実際のピン出力を決定します。
extern uint8_t f0_state, f1_state, f2_state, f3_state, f4_state;
extern uint8_t f5_state, f6_state, f7_state, f8_state;
extern uint8_t f9_state, f10_state, f11_state, f12_state;


// ============================================================================
//  出力制御 関数プロトタイプ
// ============================================================================

// ----------------------------------------------------------------------------
// 出力ピン、タイマー(PWM)の初期化
//   マイコン起動時に呼ばれ、GPIOやPWM生成用タイマー(TIM1等)を設定します。
//   BEMF機能(20ピン)が有効な場合はADCの初期化もここから呼び出されます。
// ----------------------------------------------------------------------------
void Outputs_Init(void);

// ----------------------------------------------------------------------------
// 実際のピン(GPIO/PWM)への出力更新
//   現在の方向(current_dir)、速度(current_speed)、ファンクション状態に基づき、
//   CV値(Vstart, Vmid, Vhighなど)を計算して、ハードウェアに最終的な出力状態を反映させます。
// ----------------------------------------------------------------------------
void Update_Outputs(void);

// ----------------------------------------------------------------------------
// コマンドステーションへの応答(Ack)送信
//   CVの読み書き時などに「コマンドを受け付けた」というサインを返すため、
//   モーターやライトを一瞬だけ駆動し、コマンドステーションが検知できる電流を消費させます。
// ----------------------------------------------------------------------------
void Send_Ack(void);

// ----------------------------------------------------------------------------
// ポイント(分岐器)の駆動実行
//   ポイントデコーダ専用処理。指定された方向(target_dir)に合わせて、
//   CVに設定された時間、出力強度でソレノイドにパルス電流を流します。
// ----------------------------------------------------------------------------
void Execute_Turnout(uint8_t target_dir);

// ----------------------------------------------------------------------------
// 1msごとの定期タスク処理
//   メインループ内で1ミリ秒経過するごとに呼び出されます。
//   モメンタム(CV3, CV4による滑らかな加減速)、進行方向転換時のポーズ処理、
//   キックスタートのタイマー減算、BEMFの定期サンプリング管理などを実行します。
// ----------------------------------------------------------------------------
void Process_1ms_Timer_Tasks(void);

#ifdef HAS_MOTOR_OUTPUT
// ----------------------------------------------------------------------------
// モーターPWM周波数の更新
//   CV9の設定値に基づき、PWMのキャリア周波数(32kHz, 8kHz, 2kHz, 500Hz等)を
//   タイマーの分周比(プリスケーラ)と周期(オートリロード)を再計算して設定します。
// ----------------------------------------------------------------------------
void Update_PWM_Freq(void);
#endif

#endif