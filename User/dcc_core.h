#ifndef DCC_CORE_H // [cite: 4]
#define DCC_CORE_H // [cite: 4]

#include "decoder_config.h" // [cite: 4]

// ============================================================================ // [cite: 4]
//  マクロ定義 // [cite: 4]
// ============================================================================ // [cite: 4]

// DCCパケットを一時保存するバッファの最大サイズ // [cite: 4]
// 通常のDCCパケットは3〜5バイト程度ですが、余裕を持たせて6バイトとしています。 // [cite: 4]
#define DCC_BUF_SIZE 6 // [cite: 4]

// ============================================================================ // [cite: 4]
//  グローバル変数 (外部参照用) // [cite: 4]
//  ※ 割り込み処理(ISR)内で値が書き換わるため、すべて `volatile` を付与しています。 // [cite: 4]
// ============================================================================ // [cite: 4]

// 受信したDCCパケットの生データを格納する配列 // [cite: 4]
extern volatile uint8_t packet_buffer[DCC_BUF_SIZE]; // [cite: 4]

// パケットの受信完了を示すフラグ (1 = 処理待ちのパケットあり, 0 = なし) // [cite: 5]
extern volatile uint8_t packet_ready; // [cite: 5]

// 現在受信、格納しているパケットのバイト数（データ長）を示すカウンタ // [cite: 5]
extern volatile uint8_t byte_index; // [cite: 5]

// ============================================================================ // [cite: 6]
//  関数プロトタイプ // [cite: 6]
// ============================================================================ // [cite: 6]

// ---------------------------------------------------------------------------- // [cite: 6]
// 外部割り込みハンドラ (EXTI7_0) // [cite: 6]
//   DCC信号のエッジ（立ち上がり、立ち下がり）を検知して呼び出されます。 // [cite: 6]
//   WCHマイコン特有の高速割り込み属性 (`WCH-Interrupt-fast`) を指定し、 // [cite: 6]
//   レジスタ退避のオーバーヘッドを減らして高速に信号を取り込みます。 // [cite: 6]
// ---------------------------------------------------------------------------- // [cite: 6]
void EXTI7_0_IRQHandler(void) __attribute__((interrupt("WCH-Interrupt-fast"))); // [cite: 6]

// ---------------------------------------------------------------------------- // [cite: 7]
// パケット解釈関数群 // [cite: 7]
//   メインループ内で `packet_ready` が 1 になった際に、パケットの種類に応じて // [cite: 7]
//   以下のいずれかの関数にデータが渡され、具体的な処理が実行されます。 // [cite: 7]
// ---------------------------------------------------------------------------- // [cite: 7]

// サービスモード (プログラミングトラックでのCV読み書き) コマンドを処理する関数 // [cite: 7]
//   引数: buf = パケットデータのポインタ, len = パケットのバイト長 // [cite: 7]
void Process_Service_Mode(volatile uint8_t *buf, uint8_t len); // [cite: 7]

// アクセサリー (ポイントや信号機など) コマンドを処理する関数 // [cite: 8]
//   引数: buf = パケットデータのポインタ (アドレス長が固定のためlenは省略) // [cite: 8]
void Process_Accessory_Command(volatile uint8_t *buf); // [cite: 8]

// モバイルデコーダ (車両の速度、方向、ファンクション) コマンドを処理する関数 // [cite: 9]
//   引数: buf = パケットデータのポインタ, len = バイト長, idx = データ開始位置(1 or 2) // [cite: 9]
//   ※ ショートアドレスかロングアドレスかによって、コマンドデータが格納されている // [cite: 9]
//      インデックス(idx)が異なるため、それを引数で指定します。 // [cite: 9]
void Process_Loco_Command(volatile uint8_t *buf, uint8_t len, uint8_t idx); // [cite: 9]

// ---------------------------------------------------------------------------- // [cite: 10]
// DCC受信ステートマシンのリセット関数 // [cite: 10]
//   EEPROM(Flash)への書き込み中など、一時的に割り込みが停止して // [cite: 10]
//   DCC信号のタイミングが狂った（パケットを取りこぼした）後に呼び出します。 // [cite: 10]
//   内部のカウントや状態を初期化し、次のプリアンブルから正常に受信を再開させます。 // [cite: 10]
// ---------------------------------------------------------------------------- // [cite: 10]
void Reset_DCC_State(void); // [cite: 10]

#endif // [cite: 10]