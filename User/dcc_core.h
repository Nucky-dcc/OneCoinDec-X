#ifndef DCC_CORE_H
#define DCC_CORE_H

#include "decoder_config.h"

// ============================================================================
//  マクロ定義
// ============================================================================

// ----------------------------------------------------------------------------
// DCCパケットを一時保存するバッファの最大サイズ
// ----------------------------------------------------------------------------
// 通常のDCCパケットは3〜5バイト程度（プリアンブル除く）ですが、
// POM（Programming on the Main）等の長めのパケットが来てもバッファオーバーラン
// しないよう、余裕を持たせて6バイトとして定義しています。
#define DCC_BUF_SIZE 6

// ============================================================================
//  グローバル変数 (外部参照用)
//  ※ 割り込み処理(ISR)内で値が頻繁に書き換わるため、コンパイラの最適化に
//     よる変数の読み飛ばしを防ぐ目的で、すべて `volatile` を付与しています。
// ============================================================================

// 受信したDCCパケットの生データを格納するバッファ配列
extern volatile uint8_t packet_buffer[DCC_BUF_SIZE];

// パケットの受信完了を示すフラグ (1 = 処理待ちのパケット完成, 0 = 未完了)
// 割り込み処理でパケットが完成すると1になり、メインループはこれを見て処理を開始します。
extern volatile uint8_t packet_ready;

// 現在パケットバッファの何バイト目にデータを格納しているかを示すインデックス
extern volatile uint8_t byte_index;

// ============================================================================
//  関数プロトタイプ
// ============================================================================

// ----------------------------------------------------------------------------
// 外部割り込みハンドラ (EXTI7_0)
//   DCC信号（線路電圧）のエッジ（立ち上がり、立ち下がり）を検知して
//   ハードウェアから自動的に呼び出されます。
//   WCHマイコン特有の高速割り込み属性 (`WCH-Interrupt-fast`) を指定し、
//   レジスタ退避のオーバーヘッドを減らして超高速に信号の幅を計測します。
// ----------------------------------------------------------------------------
void EXTI7_0_IRQHandler(void) __attribute__((interrupt("WCH-Interrupt-fast")));

// ----------------------------------------------------------------------------
// パケット解釈関数群
//   メインループ内で `packet_ready` が 1 になり、エラーチェック（XOR）に
//   合格したパケットの「種類」に応じて、以下のいずれかの関数に振り分けられます。
// ----------------------------------------------------------------------------

// サービスモード (プログラミングトラックでのCV読み書き) コマンドを処理する関数
//   引数: buf = パケットデータのポインタ, len = パケットのバイト長
void Process_Service_Mode(volatile uint8_t *buf, uint8_t len);

// アクセサリー (ポイントや信号機など) コマンドを処理する関数
//   引数: buf = パケットデータのポインタ (アドレス長が固定のためlenは省略)
void Process_Accessory_Command(volatile uint8_t *buf);

// モバイルデコーダ (機関車・車両の速度、方向、ファンクション) コマンドを処理する関数
//   引数: buf = パケットデータのポインタ, len = バイト長, idx = データ開始位置(1 or 2)
//   ※ ショートアドレス(1バイト)かロングアドレス(2バイト)かによって、
//      命令(コマンド)データが格納されているインデックス(idx)が異なるため、
//      それを引数で指定して解析をスタートさせます。
void Process_Loco_Command(volatile uint8_t *buf, uint8_t len, uint8_t idx);

// ----------------------------------------------------------------------------
// DCC受信ステートマシンのリセット関数
//   EEPROM(Flash)への書き込み中など、一時的に割り込みが停止して
//   DCC信号のタイミングが狂った（パケットの途中で途切れた）直後に呼び出します。
//   内部のカウントや状態を初期化し、次のプリアンブルから正常に受信を再開させます。
// ----------------------------------------------------------------------------
void Reset_DCC_State(void);

#endif