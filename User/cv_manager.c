// ----------------------------------------------------------------------------
// 任意のCV番号の値を読み出す関数
//   引数:   cv_number (1-64)
//   戻り値: キャッシュされているCV値。範囲外の指定時は 0 を返す。
// ----------------------------------------------------------------------------
uint8_t Read_CV(uint16_t cv_number) { 
    return (cv_number > 0 && cv_number <= CV_DATA_SIZE) ? cv_cache[cv_number - 1] : 0; 
}

// ----------------------------------------------------------------------------
// キャッシュ(RAM)の内容をFlashメモリへ一括保存する関数
//   注意: Flash書き込み中はCPUの処理が一時停止するため、DCC信号の受信処理が
//         破綻しないよう、割り込み制御を厳密に行います。
// ----------------------------------------------------------------------------
void EEPROM_SaveAll(void) {
    // 1. 書き込み中のDCC割り込みによるシステムクラッシュや誤作動を防止
    NVIC_DisableIRQ(DCC_IRQn); 

    // 2. Flashメモリのロック解除とエラーフラグのクリア
    FLASH_Unlock();
    FLASH_ClearFlag(FLASH_FLAG_BSY | FLASH_FLAG_EOP | FLASH_FLAG_WRPRTERR);
    
    // 3. 該当の1ページ(64バイト)を全消去
    FLASH_ErasePage(CV_FLASH_PAGE_ADDR);
    
    // 4. CH32V003の仕様に基づき、16bit(HalfWord)単位で書き込みを実行
    for(uint16_t i = 0; i < CV_DATA_SIZE; i += 2) {
        // 隣り合う2つの8bit(1byte)データを結合し、1つの16bitデータを作成
        uint16_t half_word = cv_cache[i] | ((uint16_t)cv_cache[i+1] << 8);
        FLASH_ProgramHalfWord(CV_FLASH_PAGE_ADDR + i, half_word);
    }
    
    // 5. 書き込み完了後、Flashを再度ロック
    FLASH_Lock();
    
    // 6. 割り込み禁止中にパケットを取りこぼしている可能性が高いため、
    //    DCCの受信状態を初期状態にリセットして次のパケットに備える
    Reset_DCC_State(); 
    
    // 7. DCC割り込みを再開
    NVIC_EnableIRQ(DCC_IRQn);
}

// ----------------------------------------------------------------------------
// 起動時の初期化処理
//   電源投入時に呼ばれ、FlashからRAMへデータをコピーします。
// ----------------------------------------------------------------------------
void EEPROM_Init(void) {
    // 1. Flash領域のデータをRAMのキャッシュ配列に直接コピー
    for(uint16_t i = 0; i < CV_DATA_SIZE; i++) {
        cv_cache[i] = *(volatile uint8_t*)(CV_FLASH_PAGE_ADDR + i);
    }
    
    // 2. 初期化判定
    //    書き込まれたことがないFlashメモリは全ビットが1(0xFF)になります。
    //    CV8(メーカーID)が0xFFの場合は未初期化と判断し、初期値を流し込みます。
    if(cv_cache[7] == 0xFF) { 
        for(uint16_t i = 0; i < CV_DATA_SIZE; i++) cv_cache[i] = Default_CV_Tab[i];
        EEPROM_SaveAll(); 
    }
    
    // 3. ポイントデコーダ向けの前回状態(開通方向)の復元
    //    CV64(インデックス63)に保存された状態を読み出します。
    //    万が一不正な値(2以上)が入っていた場合は 0(デフォルト) に補正します。
    current_point_dir = cv_cache[63];
    if (current_point_dir > 1) current_point_dir = 0;
}

// ----------------------------------------------------------------------------
// 任意のCV番号へ値を書き込む関数
//   引数: cv_number (1-64), value (書き込む値)
// ----------------------------------------------------------------------------
void Write_CV(uint16_t cv_number, uint8_t value) {
    // CV番号を配列のインデックス番号(0-63)に変換
    uint16_t index = cv_number - 1;

    if(index >= CV_DATA_SIZE)
        return;

    // CV7 : バージョン番号（読取専用）
    if (cv_number == 7)
        return;

    // CV8 : メーカーID（読取専用）ただし値8を書き込んだ場合のみファクトリーリセットを実行
    if (cv_number == 8) {
        if (value == 8) {
            for(uint16_t i = 0; i < CV_DATA_SIZE; i++)
                cv_cache[i] = Default_CV_Tab[i];

            EEPROM_SaveAll();

#ifdef HAS_MOTOR_OUTPUT
            Update_PWM_Freq();
#endif
        }

        return;
    }

        // --- 通常の書き込み処理 ---
        // Flashメモリは書き換え可能回数に寿命があるため、
        // 既存の値と違う値が書き込まれた場合のみ、Flashへの書き込みを実行します。
    if (cv_cache[index] != value)
    {
        cv_cache[index] = value;

        EEPROM_SaveAll();

#if defined(HAS_MOTOR_OUTPUT) && !defined(TARGET_8PIN_POINT)
            // モータPWM周波数の設定(CV9)が変更された場合は、即座にハードウェアに反映
        if (cv_number == 9)
            Update_PWM_Freq();
#endif
    }
}