/*******************************************************************************
 * 関数名: Read_CV
 * 役割  : 任意のCV番号の値を読み出す関数
 * 引数  : cv_number (1-64。DCCの仕様で1から始まります)
 * 戻り値: キャッシュされているCV値。範囲外の指定時は安全のため 0 を返す。
 *******************************************************************************/
uint8_t Read_CV(uint16_t cv_number) { 
    // 配列のインデックスは0から始まるため、cv_number から1を引いた位置にアクセスします。
    return (cv_number > 0 && cv_number <= CV_DATA_SIZE) ? cv_cache[cv_number - 1] : 0; 
}

/*******************************************************************************
 * 関数名: EEPROM_SaveAll
 * 役割  : キャッシュ(RAM)の内容をFlashメモリ(EEPROM領域)へ一括保存する関数
 * 補足  : Flash書き込み中はCPUの処理が一時停止するため、DCC信号の受信処理が
 *         破綻しないよう、割り込み制御を厳密に行います。
 *******************************************************************************/
void EEPROM_SaveAll(void) {
    // ------------------------------------------------------------------------
    // 1. 書き込み中のDCC割り込みによるシステムクラッシュや誤作動を防止
    // ------------------------------------------------------------------------
    NVIC_DisableIRQ(DCC_IRQn); 

    // ------------------------------------------------------------------------
    // 2. Flashメモリのロック解除とエラーフラグのクリア
    // ------------------------------------------------------------------------
    FLASH_Unlock();
    FLASH_ClearFlag(FLASH_FLAG_BSY | FLASH_FLAG_EOP | FLASH_FLAG_WRPRTERR);
    
    // ------------------------------------------------------------------------
    // 3. 該当の1ページ(64バイト)を全消去
    // Flashは「上書き」ができないため、指定ページを丸ごと消去(0xFF)します。
    // ------------------------------------------------------------------------
    FLASH_ErasePage(CV_FLASH_PAGE_ADDR);
    
    // ------------------------------------------------------------------------
    // 4. CH32V003の仕様に基づき、16bit(HalfWord)単位で書き込みを実行
    // CH32V003のFlashは1バイトずつの書き込みをサポートしていないため、
    // RAMから2バイトずつ取り出して結合し、16bit単位で書き込んでいきます。
    // ------------------------------------------------------------------------
    for(uint16_t i = 0; i < CV_DATA_SIZE; i += 2) {
        // 隣り合う2つの8bit(1byte)データを結合し、1つの16bitデータを作成 (リトルエンディアン)
        uint16_t half_word = cv_cache[i] | ((uint16_t)cv_cache[i+1] << 8);
        FLASH_ProgramHalfWord(CV_FLASH_PAGE_ADDR + i, half_word);
    }
    
    // ------------------------------------------------------------------------
    // 5. 書き込み完了後、誤消去を防ぐためFlashを再度ロック
    // ------------------------------------------------------------------------
    FLASH_Lock();
    
    // ------------------------------------------------------------------------
    // 6. パケット取りこぼし対策
    // 割り込み禁止中に受信中だったDCCパケットは壊れている可能性が高いため、
    // DCCの受信状態を初期状態にリセットして次のパケットに備える
    // ------------------------------------------------------------------------
    Reset_DCC_State(); 
    
    // ------------------------------------------------------------------------
    // 7. 安全が確保できたのでDCC割り込みを再開
    // ------------------------------------------------------------------------
    NVIC_EnableIRQ(DCC_IRQn);
}

/*******************************************************************************
 * 関数名: EEPROM_Init
 * 役割  : 起動時の初期化処理
 * 補足  : 電源投入時に呼ばれ、FlashからRAMへデータをコピーします。
 *         未初期化時はデフォルト値を書き込みます。
 *******************************************************************************/
void EEPROM_Init(void) {
    // ------------------------------------------------------------------------
    // 1. Flash領域のデータをRAMのキャッシュ配列に直接コピー
    // Flash空間はメモリマップ上に配置されているため、ポインタを使って直接読み出せます。
    // ------------------------------------------------------------------------
    for(uint16_t i = 0; i < CV_DATA_SIZE; i++) {
        cv_cache[i] = *(volatile uint8_t*)(CV_FLASH_PAGE_ADDR + i);
    }
    
    // ------------------------------------------------------------------------
    // 2. 初期化判定
    // 書き込まれたことがない(消去された)Flashメモリは全ビットが1(0xFF)になります。
    // CV8(メーカーID)が0xFFの場合は未初期化と判断し、初期値を流し込んで
    // Flashに保存(EEPROM_SaveAll)することで、初回セットアップを自動完了させます。
    // ------------------------------------------------------------------------
    if(cv_cache[7] == 0xFF) { 
        for(uint16_t i = 0; i < CV_DATA_SIZE; i++) cv_cache[i] = Default_CV_Tab[i];
        EEPROM_SaveAll(); 
    }
    
    // ------------------------------------------------------------------------
    // 3. ポイントデコーダ向けの前回状態(開通方向)の復元
    // 電源投入時に、前回のポイントの向きを復元します。
    // CV64(インデックス63)に保存された状態を読み出します。
    // 万が一不正な値(2以上)が入っていた場合は 0(デフォルト) に補正します。
    // ------------------------------------------------------------------------
    current_point_dir = cv_cache[63];
    if (current_point_dir > 1) current_point_dir = 0;
}

/*******************************************************************************
 * 関数名: Write_CV
 * 役割  : 任意のCV番号へ値を書き込む関数
 * 引数  : cv_number (1-64), value (書き込む値 0-255)
 * 補足  : 値に変更があった場合のみFlash保存を呼ぶことで寿命を節約します。
 *         CV7・CV8の読み取り専用の保護ロジックを実装済みです。
 *******************************************************************************/
void Write_CV(uint16_t cv_number, uint8_t value) {
    // 配列操作のため、CV番号を0始まりのインデックス番号(0-63)に変換
    uint16_t index = cv_number - 1;

    // 定義されているCV領域(64バイト)を超えている場合は無視する
    if(index >= CV_DATA_SIZE)
        return;

    // --------------------------------------------------------------------
    // --- 読み取り専用CVのガード処理 ---
    // --------------------------------------------------------------------
    // CV7 : バージョン番号（読取専用のため変更不可）
    if (cv_number == 7)
        return;

    // CV8 : メーカーID（読取専用）
    // ただし、DCC規格の慣例として「値8」を書き込んだ場合のみ、
    // 全てのCVを工場出荷状態に戻す「ファクトリーリセット」を実行します。
    if (cv_number == 8) {
        if (value == 8) {
            // 初期値をキャッシュに流し込み、Flashに一括保存
            for(uint16_t i = 0; i < CV_DATA_SIZE; i++)
                cv_cache[i] = Default_CV_Tab[i];

            EEPROM_SaveAll();

            // モーター出力がある場合、リセットされたCV9の設定に合わせてPWM周波数を再計算
#ifdef HAS_MOTOR_OUTPUT
            Update_PWM_Freq();
#endif
        }
        // CV8への書き込み要求は（リセットであれ通常値であれ）ここで処理を抜ける
        return; 
    }

    // --------------------------------------------------------------------
    // --- 通常の書き込み処理 ---
    // Flashメモリは書き換え可能回数（約10万回）に寿命があるため、
    // 既存の値と「違う値」が要求された場合のみ、Flashへの書き換えを実行します。
    // --------------------------------------------------------------------
    if (cv_cache[index] != value)
    {
        cv_cache[index] = value;

        EEPROM_SaveAll();

        // モータPWM周波数の設定(CV9)が変更された場合は、次回の再起動を待たずに
        // 即座にハードウェアのタイマー設定(PWMキャリア周波数)に反映させます。
#if defined(HAS_MOTOR_OUTPUT) && !defined(TARGET_8PIN_POINT)
        if (cv_number == 9)
            Update_PWM_Freq();
#endif
    }
}